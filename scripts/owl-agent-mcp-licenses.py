#!/usr/bin/env python3
"""Write or check the crates.io dependencies compiled into owltype-mcp and their licenses.

The list lives in rust/crates/owl-agent-mcp/THIRD-PARTY-CRATES.md, so the corresponding-source
archive carries it; Cargo.lock pins the exact versions. `--check` (in the gate) fails when the
lock file and the list disagree or a license is not one the helper's notices cover.

    python3 scripts/owl-agent-mcp-licenses.py [--check]
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "rust/crates/owl-agent-mcp/THIRD-PARTY-CRATES.md"
CRATE = "owl-agent-mcp"
# Every license expression must name at least one of these; the App ships their texts in
# Contents/SharedSupport/licenses.
COVERED = {"MIT", "Apache-2.0"}


def crates() -> list[tuple[str, str, str]]:
    # cargo tree resolves features as `cargo build -p owl-agent-mcp` does; cargo metadata would
    # unify them across the workspace and list crates the helper never compiles.
    rows: set[tuple[str, str, str]] = set()
    output = subprocess.check_output(
        ["cargo", "tree", "--locked", "--offline", "--manifest-path", str(ROOT / "rust/Cargo.toml"),
         "-p", CRATE, "-e", "normal,build", "--target", "aarch64-apple-darwin", "--prefix", "none",
         "--format", "{p}|{l}"],
        text=True,
    )
    for line in output.splitlines():
        package, _, license = line.partition("|")
        if "(/" in package:  # a workspace path crate, not crates.io
            continue
        name, version = package.split()[:2]
        rows.add((name, version.removeprefix("v"), license.strip() or "UNKNOWN"))
    return sorted(rows)


def render(rows: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Crates compiled into owltype-mcp",
        "",
        "Generated by `scripts/owl-agent-mcp-licenses.py` from `rust/Cargo.lock`; the gate checks it.",
        "Sources are the crates.io releases at these exact versions. The helper ships in",
        "`Owltype.app/Contents/Helpers/owltype-mcp`; the MIT and Apache-2.0 texts are in",
        "`Contents/SharedSupport/licenses`. rmcp is the official MCP Rust SDK",
        "(https://github.com/modelcontextprotocol/rust-sdk).",
        "",
        "| Crate | Version | License |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {name} | {version} | {license} |" for name, version, license in rows]
    return "\n".join(lines) + "\n"


def main() -> None:
    rows = crates()
    uncovered = [f"{name} {version}: {license}" for name, version, license in rows
                 if not COVERED & set(re.findall(r"[A-Za-z0-9.-]+", license))]
    if uncovered:
        sys.exit("FAIL: licenses not covered by the shipped texts: " + "; ".join(uncovered))
    text = render(rows)
    if sys.argv[1:] == ["--check"]:
        if not LIST.is_file() or LIST.read_text() != text:
            sys.exit(f"FAIL: {LIST.relative_to(ROOT)} is stale; run scripts/owl-agent-mcp-licenses.py")
        print(f"owltype-mcp crate licenses: ok ({len(rows)} crates)")
    elif not sys.argv[1:]:
        LIST.write_text(text)
        print(f"wrote {LIST.relative_to(ROOT)} ({len(rows)} crates)")
    else:
        sys.exit("usage: owl-agent-mcp-licenses.py [--check]")


if __name__ == "__main__":
    main()
